// Patch biology and comics if needed (8 questions)
function ensureEight(arr, p, L) {
  const x = [...arr];
  while (x.length < 8) {
    x.push(
      q(`سياق ${L} و${p.n}: أي أدق؟`, [`ثقافة وطنية وخليجية`, "لا علاقة", "قطب", "غابات الأمازون"], 0),
    );
  }
  return x.slice(0, 8);
}

function buildQuestions(profile) {
  const bank = {};
  for (const id of Object.keys(AR)) {
    bank[id] = ensureEight(packFor(profile, id), profile, AR[id]);
  }
  return bank;
}

